#!/bin/bash

# Проверяем, запущен ли скрипт от имени root (через sudo)
if [ "$EUID" -ne 0 ]; then
  echo "Ошибка: Этот скрипт необходимо запускать с правами sudo (sudo ./install_clevo_kb.sh)"
  exit 1
fi

echo "=== Шаг 1: Проверка наличия Git ==="
# Проверяем, установлена ли утилита git в системе
if ! command -v git &> /dev/null; then
    echo "=========================================================="
    echo "ОШИБКА: установите git перед запуском этого скрипта."
    echo "Вы можете сделать это командой: sudo apt install git"
    echo "=========================================================="
    exit 1
else
    echo "[ОК] Утилита git найдена в системе."
fi

echo -e "\n=== Шаг 3: Клонирование репозитория clevo-keyboard ==="
# Клонируем репозиторий во временную папку в директории /tmp
TARGET_DIR="/tmp/clevo-keyboard"

if [ -d "$TARGET_DIR" ]; then
    echo "Удаление старой временной папки..."
    rm -rf "$TARGET_DIR"
fi

git clone https://github.com "$TARGET_DIR"
cd "$TARGET_DIR" || exit 1

echo -e "\n=== Шаг 4: Запуск скрипта установки драйверов ==="
# Делаем встроенный установщик исполняемым и запускаем его
chmod +x kb.sh
if ./kb.sh; then
    echo -e "\n[УСПЕХ] Драйверы клавиатуры Clevo успешно установлены через DKMS!"
else
    echo -e "\n[ОШИБКА] Произошла ошибка во время компиляции или установки драйвера."
    exit 1
fi

echo -e "\n=== Шаг 5: Настройка параметров модуля (Цвет по умолчанию) ==="
# Устанавливаем белый цвет подсветки при старте.
echo "options tuxedo_keyboard color=WHITE" > /etc/modprobe.d/tuxedo_keyboard.conf
echo "[ОК] Цвет подсветки по умолчанию установлен: БЕЛЫЙ."

echo -e "\n=== Шаг 6: Очистка временных файлов ==="
rm -rf "$TARGET_DIR"
echo "[ОК] Временные файлы удалены."

echo "=========================================================="
echo "Установка завершена! Обязательно ПЕРЕЗАГРУЗИТЕ ноутбук."
echo "После перезагрузки вы сможете управлять подсветкой"
echo "с помощью комбинаций клавиш Fn + стрелки (или Fn + NumPad)."
echo "=========================================================="
